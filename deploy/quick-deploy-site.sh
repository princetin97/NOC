#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

REPO_URL=""
BRANCH="main"
INSTALL_DIR="/opt/network-monitor"
ENV_FILE=""
SITE_NAME="$(hostname -s 2>/dev/null || echo site-01)"
PUBLIC_HOST=""
UI_PORT="8080"
API_PORT="4000"
POSTGRES_USER="monitor"
POSTGRES_DB="device_monitor"
POSTGRES_PASSWORD=""
JWT_SECRET=""
AUTH_BOOTSTRAP_TOKEN=""
ALLOW_INSECURE_DEFAULTS="false"

print_usage() {
  cat <<'USAGE'
Usage:
  ./deploy/quick-deploy-site.sh \
    --repo <git_repo_url> \
    [--branch main] \
    [--dir /opt/network-monitor] \
    [--site-name hanoi-site] \
    [--public-host noc.example.com] \
    [--ui-port 8080] \
    [--api-port 4000] \
    [--bootstrap-token your-bootstrap-token] \
    [--env /opt/network-monitor/.env]

Example:
  ./deploy/quick-deploy-site.sh \
    --repo git@github.com:your-org/network-monitor.git \
    --branch main \
    --site-name site-a \
    --public-host 10.10.10.20

Then bootstrap the first admin account:
  curl -X POST http://10.10.10.20:4000/api/auth/bootstrap \
    -H 'Content-Type: application/json' \
    -d '{"token":"<AUTH_BOOTSTRAP_TOKEN>","username":"admin","password":"ChangeMe123!"}'
USAGE
}

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "Missing required command: $1" >&2
    exit 1
  }
}

random_secret() {
  openssl rand -hex 32
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --repo)
      REPO_URL="${2:-}"
      shift 2
      ;;
    --branch)
      BRANCH="${2:-}"
      shift 2
      ;;
    --dir)
      INSTALL_DIR="${2:-}"
      shift 2
      ;;
    --env)
      ENV_FILE="${2:-}"
      shift 2
      ;;
    --site-name)
      SITE_NAME="${2:-}"
      shift 2
      ;;
    --public-host)
      PUBLIC_HOST="${2:-}"
      shift 2
      ;;
    --ui-port)
      UI_PORT="${2:-}"
      shift 2
      ;;
    --api-port)
      API_PORT="${2:-}"
      shift 2
      ;;
    --bootstrap-token)
      AUTH_BOOTSTRAP_TOKEN="${2:-}"
      shift 2
      ;;
    -h|--help)
      print_usage
      exit 0
      ;;
    *)
      echo "Unknown argument: $1" >&2
      print_usage
      exit 1
      ;;
  esac
done

if [[ -z "$REPO_URL" ]]; then
  echo "Missing required --repo argument." >&2
  print_usage
  exit 1
fi

if [[ -z "$PUBLIC_HOST" ]]; then
  PUBLIC_HOST="$(hostname -I 2>/dev/null | awk '{print $1}')"
fi

if [[ -z "$ENV_FILE" ]]; then
  ENV_FILE="${INSTALL_DIR}/.env"
fi

echo "==> Preparing host packages"
need_cmd awk
need_cmd sed
need_cmd git
need_cmd curl
need_cmd openssl

if ! command -v docker >/dev/null 2>&1 || ! docker compose version >/dev/null 2>&1; then
  echo "==> Docker or Docker Compose plugin not found. Installing..."
  if [[ ! -x "${SCRIPT_DIR}/setup-ubuntu-24.04.sh" ]]; then
    chmod +x "${SCRIPT_DIR}/setup-ubuntu-24.04.sh"
  fi

  if [[ "$(id -u)" -eq 0 ]]; then
    "${SCRIPT_DIR}/setup-ubuntu-24.04.sh"
  else
    sudo "${SCRIPT_DIR}/setup-ubuntu-24.04.sh"
  fi
fi

echo "==> Resolving docker compose command"
DC=(docker compose)
if ! docker info >/dev/null 2>&1; then
  if sudo -n docker info >/dev/null 2>&1; then
    DC=(sudo docker compose)
  else
    echo "Docker daemon is not accessible. Re-login or run with a user that can access Docker." >&2
    exit 1
  fi
fi

echo "==> Cloning/updating repository"
mkdir -p "$(dirname "$INSTALL_DIR")"
if [[ -d "${INSTALL_DIR}/.git" ]]; then
  git -C "$INSTALL_DIR" fetch --all --prune
  git -C "$INSTALL_DIR" checkout "$BRANCH"
  git -C "$INSTALL_DIR" pull --ff-only origin "$BRANCH"
else
  rm -rf "$INSTALL_DIR"
  git clone --branch "$BRANCH" "$REPO_URL" "$INSTALL_DIR"
fi

if [[ -z "$POSTGRES_PASSWORD" ]]; then
  POSTGRES_PASSWORD="$(random_secret)"
fi
if [[ -z "$JWT_SECRET" ]]; then
  JWT_SECRET="$(random_secret)"
fi
if [[ -z "$AUTH_BOOTSTRAP_TOKEN" ]]; then
  AUTH_BOOTSTRAP_TOKEN="$(random_secret)"
fi

echo "==> Writing environment file"
if [[ -f "$ENV_FILE" ]]; then
  cp "$ENV_FILE" "${ENV_FILE}.bak.$(date +%Y%m%d%H%M%S)"
fi

cat >"$ENV_FILE" <<EOF
# Auto-generated by deploy/quick-deploy-site.sh
SITE_NAME=${SITE_NAME}
POSTGRES_USER=${POSTGRES_USER}
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
POSTGRES_DB=${POSTGRES_DB}
JWT_SECRET=${JWT_SECRET}
AUTH_BOOTSTRAP_TOKEN=${AUTH_BOOTSTRAP_TOKEN}
ALLOW_INSECURE_DEFAULTS=${ALLOW_INSECURE_DEFAULTS}
CORS_ORIGIN=http://${PUBLIC_HOST}:${UI_PORT}
API_PORT=${API_PORT}
POLL_INTERVAL_SECONDS=60
DISCOVERY_INTERVAL_SECONDS=3600
SNMP_TIMEOUT_MS=3000
SNMP_RETRIES=1
EOF

echo "==> Starting platform"
cd "$INSTALL_DIR"
COMPOSE_FILE=""
for candidate in docker-compose.yml docker-compose.yaml compose.yml compose.yaml; do
  if [[ -f "$INSTALL_DIR/$candidate" ]]; then
    COMPOSE_FILE="$INSTALL_DIR/$candidate"
    break
  fi
done

if [[ -z "$COMPOSE_FILE" ]]; then
  echo "No Docker Compose file found in $INSTALL_DIR" >&2
  echo "Expected one of: docker-compose.yml, docker-compose.yaml, compose.yml, compose.yaml" >&2
  exit 1
fi

"${DC[@]}" -f "$COMPOSE_FILE" up -d --build

echo "==> Waiting for API health"
for _ in $(seq 1 60); do
  if curl -fsS "http://127.0.0.1:${API_PORT}/api/health" >/dev/null 2>&1; then
    break
  fi
  sleep 2
done

if ! curl -fsS "http://127.0.0.1:${API_PORT}/api/health" >/dev/null 2>&1; then
  echo "API health check failed. Check logs:"
  echo "  ${DC[*]} -f $COMPOSE_FILE logs --tail 200 api"
  exit 1
fi

echo
echo "Deployment completed successfully."
echo "UI URL:  http://${PUBLIC_HOST}:${UI_PORT}"
echo "API URL: http://${PUBLIC_HOST}:${API_PORT}/api/health"
echo "Bootstrap token: ${AUTH_BOOTSTRAP_TOKEN}"
echo "Install dir: ${INSTALL_DIR}"
echo "Env file: ${ENV_FILE}"
echo
echo "Bootstrap first admin (run once when there are no users yet):"
echo "  curl -X POST http://${PUBLIC_HOST}:${API_PORT}/api/auth/bootstrap -H 'Content-Type: application/json' -d '{\"token\":\"${AUTH_BOOTSTRAP_TOKEN}\",\"username\":\"admin\",\"password\":\"ChangeMe123!\"}'"
echo
echo "Useful commands:"
echo "  cd ${INSTALL_DIR}"
echo "  ${DC[*]} -f $COMPOSE_FILE ps"
echo "  ${DC[*]} -f $COMPOSE_FILE logs -f api"
echo "  ${DC[*]} -f $COMPOSE_FILE logs -f poller"
